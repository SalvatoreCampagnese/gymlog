export const GENERIC_FOODS = RAW.map(([name, kcal, protein, carbs, fat, portion]) => ({
  key: `gen:${name}`,
  name,
  per100: { kcal, protein, carbs, fat },
  servingGrams: portion,
  source: "generic" as const,
}));

const n = (s: string) =>
  s.toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "");

export function searchGeneric(q: string) {
  const words = n(q).split(/\s+/).filter(Boolean);
  if (!words.length) return [];
  return GENERIC_FOODS.filter((f) => words.every((w) => n(f.name).includes(w))).slice(0, 8);
}
